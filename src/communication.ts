import { type eventContents, type eventMessage } from "./event";

/**
 * Control message sent from a client page to the shared worker port on unload to close and unsubscribe
 */
export interface communicationDisconnect {
    /**
     * Marker flag indicating the client port is disconnecting
     */
    disconnect: true;
}

/**
 * Heartbeat payload broadcast by the shared worker to client ports reporting backend transport connectivity
 */
export interface communicationStatus {
    /**
     * Whether the shared worker's transport is currently connected
     */
    connected: boolean;
}

/**
 * Event message payload sent across shared worker message ports, carrying an optional identifier for cross-worker peer deduplication
 * @template eventContentsType The type of the event's payload contents
 */
export interface communicationEventMessage<eventContentsType = eventContents> extends eventMessage<eventContentsType> {
    /**
     * Optional unique identifier generated by the originating page to suppress duplicate peer broadcasts across multiple shared workers
     */
    id?: string;
}

/**
 * Timeout in milliseconds after which a client treats missing worker heartbeats as lost communication
 */
export const communicationTimeout: number = 500;
